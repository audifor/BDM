import { beforeAll, describe, expect, it, vi } from 'vitest';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { createWorldDbV2GameFromSnapshot, projectWorldDbV2, worldDbV2Repository } from './WorldDbV2Game';
import type { WorldDbV2Snapshot } from '@/tauri/TauriWorldDbV2';
import { useGameStore } from '@/stores/gameStore';
import { getUserTeam } from '@/engine/calendar';
import { calculateStandings } from '@/engine/competition/standings';
import { getTeamRoster, validateGameWorld, type GameWorld } from '@/domain/world';
import { PLAYER_TRUTH_RATING_KEYS } from '@/domain/player/PlayerTruthCatalog';
import { saveCurrentGame, loadSavedGame } from '@/app/save/GameSaveService';
import { projectPersistentWorldTruth } from '@/save/persistentWorldTruth';
import { parseWorldCompetitionRuntimeBundle } from '@/domain/competition';
import { deserializeGameWorldSaveV4, serializeGameWorldV4 } from '@/save/GameWorldSaveV4';
import { assertWorldDbGameBootstrapSliceV1 } from '@/domain/worldDb/GameBootstrap';
import { assertWorldDbCompetitionBundleV1 } from '@/domain/worldDb/CompetitionBundle';
import { assertWorldDbSelectionCatalogV1 } from '@/domain/worldDb/SelectionCatalog';
import type { GameSaveRepository } from '@/app/save/GameSaveRepository';
vi.setConfig({ testTimeout: 600000, hookTimeout: 600000 });
const sourceRoot = process.env.WORLDDB_SOURCE_ROOT ?? 'C:/BDM_DB/WORLDDB_PBM';
const master = resolve(sourceRoot, 'WORLDDB_UNIFIED_V2/worlddb_bdm_btw_v2.sqlite');
const hash = () => createHash('sha256').update(readFileSync(master)).digest('hex');
const state = () => useGameStore.getState().world!;
const work = resolve('.worlddb-v2', 'tests-' + Date.now());
const fileRepo = (file: string): GameSaveRepository => ({ save: async (text) => { writeFileSync(file, text); }, load: async () => readFileSync(file, 'utf-8'), getInfo: async () => existsSync(file) ? { savedAt: JSON.parse(readFileSync(file, 'utf-8')).savedAt } : null });
let snapshot: WorldDbV2Snapshot, initial: GameWorld, peer: GameWorld, before: string;
describe.skipIf(!existsSync(master))('WorldDB V2 · complete PBM league through the real Courtside store and MatchEngine', () => {
    beforeAll(async () => {
        mkdirSync(work, { recursive: true });
        before = hash();
        const raw = execFileSync(process.env.BDM_PYTHON ?? 'python', ['-B', 'src-tauri/resources/worlddb_v2_bridge.py'], { input: JSON.stringify({ method: 'build', sourceRoot, output: resolve(work, 'universe.sqlite'), startDate: '2025-10-04', seed: 'playable-v2-acceptance' }), encoding: 'utf-8', maxBuffer: 128 * 1024 * 1024 });
        snapshot = JSON.parse(raw);
        writeFileSync(resolve(work, 'snapshot.json'), raw);
        initial = await createWorldDbV2GameFromSnapshot(snapshot, 'pbm:DYN_equipe:41', { firstName: 'Lucia', lastName: 'Piloto', dateOfBirth: '1990-01-01', gender: 'female', nationalityCountryCode: 'ESP', background: 'rookie', ambition: 'firstTitle', biography: 'WorldDB V2 acceptance', coachingStyle: 'balanced', disposition: 'balanced' });
        peer = await createWorldDbV2GameFromSnapshot(snapshot, 'pbm:DYN_equipe:50');
    });
    it('validates real native DTOs, immutable rules bundle and all original identities/rosters', async () => {
        const slice = projectWorldDbV2(snapshot), repository = worldDbV2Repository(slice);
        assertWorldDbGameBootstrapSliceV1(slice);
        assertWorldDbSelectionCatalogV1(await repository.loadSelectionCatalog('worlddb-v2:projection'));
        assertWorldDbCompetitionBundleV1(await repository.loadCompetitionSeason('worlddb-v2:projection', slice.season.competitionSeasonId));
        expect(parseWorldCompetitionRuntimeBundle(JSON.parse(readFileSync('src/data/worlddb-v2/competition-runtime.json', 'utf-8'))).competitionFormats.length).toBeGreaterThan(1);
        validateGameWorld(initial);
        expect(Object.keys(initial.teams)).toHaveLength(18);
        expect(Object.values(initial.teams).map(t => t.id).sort()).toEqual(snapshot.clubs.map(c => c.entity_id).sort());
        expect(Object.values(initial.teams).every(t => getTeamRoster(initial, t.id).length >= 5)).toBe(true);
        expect(Object.values(initial.players).every(p => p.id.startsWith('pbm:DYN_joueur:') && PLAYER_TRUTH_RATING_KEYS.every(k => p.basketball.ratings[k] >= 1 && p.basketball.ratings[k] <= 100))).toBe(true);
        expect(Object.values(initial.games)).toHaveLength(306);
        expect(Object.values(initial.games).every(g => g.status === 'scheduled')).toBe(true);
        expect(initial.worldDbCompetitionRuntime?.worldDbV2?.profiles).toBe('BDM_GENERATED_CANONICAL');
        expect(Object.keys(initial.facilitiesById).some(id => id.startsWith('pbm:DYN_facility:'))).toBe(true);
    });
    it('plays the real user match, registers statistics/standings, advances time and resumes native Save V4', async () => {
        const peerBefore = JSON.stringify(projectPersistentWorldTruth(peer));
        useGameStore.getState().replaceWorld(initial);
        const team = getUserTeam(state())!;
        expect(team.name).toBe('Casademont Zaragoza');
        const game = Object.values(state().games).find(g => g.date === state().currentDate && (g.homeTeamId === team.id || g.awayTeamId === team.id))!;
        expect(game).toBeDefined();
        useGameStore.getState().instantResult();
        expect(state().games[game.id]!.status).toBe('completed');
        expect(state().matchStatLogsByGameId[game.id]).toBeDefined();
        const standings = calculateStandings(state(), state().currentSeasonId!);
        expect(standings.find(row => row.teamId === team.id)!.played).toBe(1);
        expect(state().games[game.id]!.result).not.toBeNull();
        const result = await useGameStore.getState().advanceDayAsync();
        expect(result?.status).toMatch(/COMPLETED|BREAKPOINT_AFTER_PROCESSING/);
        expect(state().currentDate).toBe('2025-10-05');
        const played = state(), repo = fileRepo(resolve(work, 'native-save-v4.json'));
        await saveCurrentGame(played, repo, '2026-10-25T12:00:00Z');
        expect(JSON.parse(await repo.load()).schemaVersion).toBe(4);
        useGameStore.setState({ world: null });
        const restored = await loadSavedGame(fileRepo(resolve(work, 'native-save-v4.json')));
        expect(projectPersistentWorldTruth(restored)).toEqual(projectPersistentWorldTruth(played));
        expect(restored.worldDbCompetitionRuntime?.worldDbV2).toEqual(played.worldDbCompetitionRuntime?.worldDbV2);
        useGameStore.getState().replaceWorld(restored);
        const next = await useGameStore.getState().advanceDayAsync();
        expect(next?.status).toMatch(/COMPLETED|BREAKPOINT_AFTER_PROCESSING/);
        expect(state().currentDate).toBe('2025-10-06');
        expect(JSON.stringify(projectPersistentWorldTruth(peer))).toBe(peerBefore);
        await saveCurrentGame(peer, fileRepo(resolve(work, 'second-native-save-v4.json')), '2026-10-25T12:00:00Z');
        expect(hash()).toBe(before);
        writeFileSync(resolve(work, 'acceptance.json'), JSON.stringify({ passed: true, masterSha256: before, teams: Object.keys(initial.teams).length, players: Object.keys(initial.players).length, scheduledGames: 306, userGame: state().games[game.id], statsGames: Object.keys(state().matchStatLogsByGameId).length, currentDate: state().currentDate, nativeSaveVersion: 4, source: state().worldDbCompetitionRuntime?.worldDbV2 }, null, 2));
    });
    it('accepts the PBM reference date and a different fictional start without importing results', async () => {
        for (const day of ['2025-07-01', '2032-07-01']) {
            const changed = { ...snapshot, manifest: { ...snapshot.manifest, configuration: { ...snapshot.manifest.configuration, start_date: day } } };
            const world = await createWorldDbV2GameFromSnapshot(changed, 'pbm:DYN_equipe:41');
            expect(world.currentDate).toBe(day);
            expect(world.worldDbCompetitionRuntime?.worldDbV2?.fictional).toBe(true);
            expect(Object.values(world.games).every(g => g.status === 'scheduled' && g.date >= world.currentDate)).toBe(true);
        }
    });
    it('rejects incomplete native provenance instead of weakening Save V4 validation', () => {
        const save = JSON.parse(JSON.stringify(serializeGameWorldV4(initial, '2026-10-25T12:00:00Z')));
        delete save.payload.worldDbCompetitionRuntime.worldDbV2.masterSha256;
        expect(() => deserializeGameWorldSaveV4(save)).toThrow(/WorldDB V2 provenance/);
    });
});
